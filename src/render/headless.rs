//! The headless mode: rendering an image to a file without an interactive window, for the `render` command on native.
//!
//! [`render()`] sets up the world once from [`RenderOptions`], then moves the tile of a [`PathTracer`] across the image.
//! Each tile is traced to all of its samples, displayed to a texture, and read back into the image, which is then saved.
//! Tiling keeps the GPU memory used by the tile the same for any image size.
//! The interactive mode is the other user of [`PathTracer`].

use super::{gpu, path_tracer::PathTracer, world};

/// Format of the texture that each tile is displayed to before being read back.
const TILE_FORMAT: wgpu::TextureFormat = wgpu::TextureFormat::Rgba8Unorm;

/// Options for rendering an image to a file without an interactive window.
#[derive(clap::Args)]
pub(crate) struct RenderOptions {
    /// glTF 2.0 binary (.glb) scene file.
    #[arg(long, default_value = super::DEFAULT_SCENE)]
    scene: std::path::PathBuf,
    /// Skybox image file (EXR, HDR, JPEG, PNG, or WebP).
    #[arg(long, default_value = super::DEFAULT_SKYBOX)]
    skybox: std::path::PathBuf,
    /// Average skybox luminance in nits.
    #[arg(
        long,
        default_value_t = world::DEFAULT_SKYBOX_LUMINANCE,
        allow_hyphen_values = true,
        value_parser = parse_nonnegative,
    )]
    skybox_luminance: f32,
    /// Output image file (PNG, JPEG, or WebP, inferred from the extension); overwritten if it exists.
    #[arg(long, default_value = "render.png", value_parser = parse_output)]
    output: std::path::PathBuf,
    /// Output image width in pixels.
    #[arg(long, default_value_t = 1920, value_parser = clap::value_parser!(u32).range(1..))]
    width: u32,
    /// Output image height in pixels.
    #[arg(long, default_value_t = 1080, value_parser = clap::value_parser!(u32).range(1..))]
    height: u32,
    /// Samples per pixel.
    #[arg(long, default_value_t = 256, value_parser = clap::value_parser!(u32).range(1..))]
    samples: u32,
    /// Maximum number of bounces after the first surface hit; 0 evaluates direct lighting only.
    #[arg(
        long,
        default_value_t = PathTracer::DEFAULT_MAX_BOUNCES,
        value_parser = clap::value_parser!(u32).range(0..=i64::from(PathTracer::MAX_BOUNCES_LIMIT)),
    )]
    max_bounces: u32,
    /// Width and height of each tile in pixels; smaller tiles keep each GPU submission shorter.
    #[arg(long, default_value_t = 512, value_parser = clap::value_parser!(u32).range(1..))]
    tile_size: u32,
    /// Camera position in world coordinates (+X right, +Y up, -Z forward); defaults to an autogenerated camera.
    #[arg(long, value_name = "X,Y,Z", allow_hyphen_values = true, value_parser = parse_position)]
    camera_position: Option<glam::Vec3>,
    /// Camera yaw in degrees; defaults to an autogenerated camera.
    #[arg(long, allow_hyphen_values = true, value_parser = parse_finite)]
    camera_yaw: Option<f32>,
    /// Camera pitch in degrees, from -90 to 90; defaults to an autogenerated camera.
    #[arg(long, allow_hyphen_values = true, value_parser = parse_pitch)]
    camera_pitch: Option<f32>,
    /// Vertical field of view in degrees, strictly between 0 and 180; defaults to an autogenerated camera.
    #[arg(long, value_parser = parse_fov)]
    camera_fov: Option<f32>,
}

/// Parse a finite [`f32`].
fn parse_finite(value: &str) -> Result<f32, String> {
    let number = value.parse::<f32>().map_err(|error| error.to_string())?;
    if number.is_finite() {
        Ok(number)
    } else {
        Err("must be finite".to_string())
    }
}

/// Parse a finite, nonnegative [`f32`].
fn parse_nonnegative(value: &str) -> Result<f32, String> {
    let number = parse_finite(value)?;
    if number >= 0.0 {
        Ok(number)
    } else {
        Err("must be nonnegative".to_string())
    }
}

/// Parse a pitch in degrees, from -90 to 90.
fn parse_pitch(value: &str) -> Result<f32, String> {
    let pitch = parse_finite(value)?;
    if (-90.0..=90.0).contains(&pitch) {
        Ok(pitch)
    } else {
        Err("must be from -90 to 90".to_string())
    }
}

/// Parse a vertical field of view in degrees, strictly between 0 and 180.
fn parse_fov(value: &str) -> Result<f32, String> {
    let fov = parse_finite(value)?;
    if fov > 0.0 && fov < 180.0 {
        Ok(fov)
    } else {
        Err("must be strictly between 0 and 180".to_string())
    }
}

/// Parse a position written as `X,Y,Z`.
fn parse_position(value: &str) -> Result<glam::Vec3, String> {
    let coordinates = value
        .split(',')
        .map(|coordinate| parse_finite(coordinate.trim()))
        .collect::<Result<Vec<_>, _>>()?;
    match coordinates[..] {
        [x, y, z] => Ok(glam::Vec3::new(x, y, z)),
        _ => Err("must be three comma-separated coordinates".to_string()),
    }
}

/// Parse an output image path whose extension names a supported format.
fn parse_output(value: &str) -> Result<std::path::PathBuf, String> {
    let path = std::path::PathBuf::from(value);
    match image::ImageFormat::from_path(&path) {
        Ok(image::ImageFormat::Png | image::ImageFormat::Jpeg | image::ImageFormat::WebP) => {
            Ok(path)
        }
        _ => Err("must have a .png, .jpg, .jpeg, or .webp extension".to_string()),
    }
}

/// Render an image as described by `options` and save it to the output file.
#[expect(
    clippy::future_not_send,
    reason = "world loading and GPU submission run on the calling thread"
)]
pub(crate) async fn render(options: &RenderOptions) -> anyhow::Result<()> {
    let started = std::time::Instant::now();
    log::info!("Rendering {}", options.scene.display());

    let mut world = load_world(options)?;

    let instance = wgpu::Instance::new(wgpu::InstanceDescriptor {
        backends: wgpu::Backends::PRIMARY, // Vulkan, Metal, DX12
        ..wgpu::InstanceDescriptor::new_without_display_handle()
    });
    let adapter = gpu::request_adapter(&instance, None).await?;
    let (device, queue) = gpu::request_device(&adapter).await?;

    let tile_size = [
        options.tile_size.min(options.width),
        options.tile_size.min(options.height),
    ];
    let mut path_tracer = PathTracer::new(
        &device,
        &queue,
        world.take_updates(),
        tile_size,
        TILE_FORMAT,
    )?;
    path_tracer.set_max_bounces(options.max_bounces);
    drop(world); // the GPU has its own copy of the world, so free the CPU copy

    let pixels = render_tiles(options, &device, &queue, &mut path_tracer, tile_size)?;

    image::save_buffer(
        &options.output,
        &pixels,
        options.width,
        options.height,
        image::ExtendedColorType::Rgb8,
    )
    .map_err(|error| anyhow::anyhow!("cannot save {}: {error}", options.output.display()))?;
    log::info!(
        "Saved {} in {:.1}s",
        options.output.display(),
        started.elapsed().as_secs_f64()
    );
    Ok(())
}

/// Load the scene and skybox, and apply the skybox luminance and camera options.
fn load_world(options: &RenderOptions) -> anyhow::Result<world::World> {
    let scene = std::fs::read(&options.scene).map_err(|error| {
        anyhow::anyhow!("cannot read scene {}: {error}", options.scene.display())
    })?;
    let skybox = std::fs::read(&options.skybox).map_err(|error| {
        anyhow::anyhow!("cannot read skybox {}: {error}", options.skybox.display())
    })?;
    let mut world = world::World::new(
        &scene,
        &skybox,
        options.width as f32 / options.height as f32,
    )?;
    world.edit_skybox_average_luminance(options.skybox_luminance);
    world.edit_camera(|camera| {
        camera.translate_and_rotate_to(
            options.camera_position,
            options.camera_yaw.map(f32::to_radians),
            options.camera_pitch.map(f32::to_radians),
        );
        if let Some(fov) = options.camera_fov {
            camera.set_fov(fov.to_radians());
        }
    });
    Ok(world)
}

/// Trace all samples of every tile of the image, returning the image as RGB8 pixels in row-major order.
fn render_tiles(
    options: &RenderOptions,
    device: &wgpu::Device,
    queue: &wgpu::Queue,
    path_tracer: &mut PathTracer,
    tile_size: [u32; 2],
) -> anyhow::Result<Vec<u8>> {
    let image_size = [options.width, options.height];
    let readback = TileReadback::new(device, tile_size);
    let mut pixels = vec![0; options.width as usize * options.height as usize * 3];

    let started = std::time::Instant::now();
    let mut last_progress_log = started;
    let total_samples =
        u64::from(options.width) * u64::from(options.height) * u64::from(options.samples);
    let mut traced_samples = 0;

    for y in (0..options.height).step_by(tile_size[1] as usize) {
        for x in (0..options.width).step_by(tile_size[0] as usize) {
            let origin = [x, y];
            // edge tiles are cut off at the image border
            let visible_size = [
                tile_size[0].min(options.width - x),
                tile_size[1].min(options.height - y),
            ];
            path_tracer.set_tile(device, image_size, origin, tile_size)?;

            let mut remaining_samples = options.samples;
            while remaining_samples > 0 {
                let mut encoder = device.create_command_encoder(&wgpu::CommandEncoderDescriptor {
                    label: Some("Trace encoder"),
                });
                let sample_count = path_tracer.trace(
                    queue,
                    &mut encoder.begin_compute_pass(&wgpu::ComputePassDescriptor {
                        label: Some("Trace pass"),
                        timestamp_writes: None,
                    }),
                    remaining_samples,
                );
                queue.submit([encoder.finish()]);
                // waiting keeps the progress accurate and the queue short
                device.poll(wgpu::PollType::wait_indefinitely())?;
                remaining_samples -= sample_count;

                traced_samples += u64::from(visible_size[0])
                    * u64::from(visible_size[1])
                    * u64::from(sample_count);
                if last_progress_log.elapsed().as_secs() >= 1 {
                    last_progress_log = std::time::Instant::now();
                    let fraction = traced_samples as f64 / total_samples as f64;
                    let elapsed = started.elapsed().as_secs_f64();
                    log::info!(
                        "Progress {:.1}%; elapsed {elapsed:.1}s; remaining approximately {:.1}s",
                        fraction * 100.0,
                        elapsed * (1.0 - fraction) / fraction
                    );
                }
            }

            readback.read(device, queue, path_tracer, |row, rgba| {
                if row >= visible_size[1] as usize {
                    return;
                }
                let start = ((y as usize + row) * options.width as usize + x as usize) * 3;
                let rgb = &mut pixels[start..start + visible_size[0] as usize * 3];
                for (rgb, rgba) in rgb
                    .as_chunks_mut::<3>()
                    .0
                    .iter_mut()
                    .zip(rgba.as_chunks::<4>().0)
                {
                    *rgb = [rgba[0], rgba[1], rgba[2]]; // alpha is always 1
                }
            })?;
        }
    }
    Ok(pixels)
}

/// Resources for displaying the accumulated tile of a [`PathTracer`] to a texture and reading it back to the CPU.
struct TileReadback {
    /// Texture of [`TILE_FORMAT`] that the tile is displayed to.
    texture: wgpu::Texture,
    texture_view: wgpu::TextureView,
    /// Buffer that [`Self::texture`] is copied to for mapping.
    buffer: wgpu::Buffer,
    /// Size of a row of [`Self::buffer`] in bytes, padded to [`wgpu::COPY_BYTES_PER_ROW_ALIGNMENT`].
    bytes_per_row: u32,
}

impl TileReadback {
    fn new(device: &wgpu::Device, tile_size: [u32; 2]) -> Self {
        let texture = device.create_texture(&wgpu::TextureDescriptor {
            label: Some("Readback texture"),
            size: wgpu::Extent3d {
                width: tile_size[0],
                height: tile_size[1],
                depth_or_array_layers: 1,
            },
            mip_level_count: 1,
            sample_count: 1,
            dimension: wgpu::TextureDimension::D2,
            format: TILE_FORMAT,
            usage: wgpu::TextureUsages::RENDER_ATTACHMENT | wgpu::TextureUsages::COPY_SRC,
            view_formats: &[],
        });
        let bytes_per_row = (tile_size[0] * 4).next_multiple_of(wgpu::COPY_BYTES_PER_ROW_ALIGNMENT); // 4 bytes per pixel for TILE_FORMAT
        let buffer = device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("Readback buffer"),
            size: u64::from(bytes_per_row) * u64::from(tile_size[1]),
            usage: wgpu::BufferUsages::COPY_DST | wgpu::BufferUsages::MAP_READ,
            mapped_at_creation: false,
        });
        Self {
            texture_view: texture.create_view(&wgpu::TextureViewDescriptor::default()),
            texture,
            buffer,
            bytes_per_row,
        }
    }

    /// Display the accumulated tile of `path_tracer`, then call `read_row` with the index and RGBA8 pixels of each row of the tile.
    fn read(
        &self,
        device: &wgpu::Device,
        queue: &wgpu::Queue,
        path_tracer: &PathTracer,
        mut read_row: impl FnMut(usize, &[u8]),
    ) -> anyhow::Result<()> {
        let mut encoder = device.create_command_encoder(&wgpu::CommandEncoderDescriptor {
            label: Some("Readback encoder"),
        });
        path_tracer.display(&mut encoder.begin_render_pass(&wgpu::RenderPassDescriptor {
            label: Some("Display pass"),
            color_attachments: &[Some(wgpu::RenderPassColorAttachment {
                view: &self.texture_view,
                depth_slice: None,
                resolve_target: None,
                ops: wgpu::Operations {
                    load: wgpu::LoadOp::Clear(wgpu::Color::BLACK),
                    store: wgpu::StoreOp::Store,
                },
            })],
            depth_stencil_attachment: None,
            timestamp_writes: None,
            occlusion_query_set: None,
            multiview_mask: None,
        }));
        encoder.copy_texture_to_buffer(
            self.texture.as_image_copy(),
            wgpu::TexelCopyBufferInfo {
                buffer: &self.buffer,
                layout: wgpu::TexelCopyBufferLayout {
                    offset: 0,
                    bytes_per_row: Some(self.bytes_per_row),
                    rows_per_image: None,
                },
            },
            self.texture.size(),
        );
        let (sender, receiver) = std::sync::mpsc::channel();
        encoder.map_buffer_on_submit(&self.buffer, wgpu::MapMode::Read, .., move |result| {
            let _ = sender.send(result);
        });
        queue.submit([encoder.finish()]);
        device.poll(wgpu::PollType::wait_indefinitely())?;
        receiver.recv()??; // the callback has run, since polling waited for the submission

        {
            let mapped = self.buffer.get_mapped_range(..)?;
            for (row, rgba) in mapped.chunks_exact(self.bytes_per_row as usize).enumerate() {
                read_row(row, rgba);
            }
        }
        self.buffer.unmap();
        Ok(())
    }
}
